<?php

//так, я тут получаю текущую директорию, чтобы потом правильно пути прописать
$dir = __DIR__;

//формирую путь к базовому классу Equipment.php (поднимаюсь на уровень выше)
$equipment = $dir . "/../Equipment.php";
$Biological = $dir . '/Biologicals/Biological.php';

//проверяю, есть ли вообще файл с базовым классом, чтобы не словить фатальную ошибку
if(file_exists($equipment)) {
    //если файл есть — подрубаю его через require_once (чтобы дважды не грузился)
    require_once($equipment);
    //и вывожу радостное сообщение, что всё ок, файл на месте
    echo "Файл |{$equipment}| подключен!";
}

//создаю класс Tractor (трактор), который наследуется от Equipment (оборудование).
//слово final значит, что от этого трактора больше никто не сможет наследоваться.
//это типа конечный класс, венец творения.
final class Tractor extends Equipment
{
    //переопределяю метод "прикрепить к чему-то физическому"
    //(#[Override] - это типа атрибут, чтобы IDE не ругалась)
    #[\Override]
    public function attachTo(Physical $physical): Tractor
    {
        //раз мы прицепились и работаем — плюсую износ трактора на 1.0
        $this->wear += 1.0;

        //возвращаю $this (сам трактор), чтобы можно было делать цепочки вызовов,
        //типа $tractor->attachTo($x)->service(); Красиво же.
        return $this;
    }

    //тоже переопределяю метод. Это метод сервисного обслуживания.
    //тут препод рассказывал про "ковариантность" возвращаемых типов:
    //в родителе возвращается Equipment, а я тут возвращаю Tractor (более узкий тип), так можно.
    #[\Override]
    public function service(): Tractor
    //переопределение сигнатуры по правилу ковариантности
    {
        //обязательно вызываю родительский метод, чтобы не сломать базовую логику обслуживания
        parent::service();

        //а теперь дозаправляю наш трактор на 50 единиц (литров топлива?)
        $this->refuel(50.0);

        //и опять возвращаю себя любимого для удобства
        return $this;
    }
}